//! A local copy of a hosted room. The caller owns transport, retries, and the editing session.

use std::collections::VecDeque;
use std::io;

use wordcraft_doc::{ChangeSet, DocError, Document, change::Side};

const MAX_CHANGE_BYTES: usize = 256 * 1024;
const MAX_PENDING_BYTES: usize = 2 * 1024 * 1024;
const MAX_PENDING: usize = 32;

/// A submission to the hosted room. Keep these exact values on an uncertain retry.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Proposal {
    pub operation_id: String,
    pub base_revision: u64,
    pub change_json: Vec<u8>,
}

#[derive(Debug, thiserror::Error)]
pub enum ReplicaError {
    #[error("replay is missing revision {expected} before {received}")]
    Gap { expected: u64, received: u64 },
    #[error("replay clashes with pending edits: {0}")]
    Conflict(#[source] DocError),
    #[error("the accepted operation differs from the pending edit")]
    AcceptedMismatch,
    #[error("the replica requires recovery")]
    RecoveryRequired,
    #[error("the hosted room's pending edit limit was reached")]
    PendingLimit,
    #[error("the edit could not be encoded: {0}")]
    Encode(#[source] serde_json::Error),
    #[error("the change does not apply: {0}")]
    InvalidChange(#[from] DocError),
}

struct Pending {
    change: ChangeSet,
    bytes: usize,
}

/// A checkpoint and its ordered journal, with local edits visible while awaiting acceptance.
pub struct RemoteReplica {
    revision: u64,
    confirmed: Document,
    document: Document,
    pending: VecDeque<Pending>,
    in_flight: Option<Proposal>,
    needs_recovery: bool,
}

impl RemoteReplica {
    /// Start from an authoritative document with the block IDs from the room's checkpoint.
    pub fn new(revision: u64, document: Document) -> Self {
        Self { revision, confirmed: document.clone(), document, pending: VecDeque::new(), in_flight: None, needs_recovery: false }
    }

    /// Latest revision integrated from the room's ordered journal.
    pub fn revision(&self) -> u64 {
        self.revision
    }

    /// The visible document, including pending work. Preserve a copy of this during recovery.
    pub fn document(&self) -> &Document {
        &self.document
    }

    /// The room document at the last integrated revision.
    pub fn confirmed(&self) -> &Document {
        &self.confirmed
    }

    pub fn pending_len(&self) -> usize {
        self.pending.len()
    }

    /// Locate an anchor pair from the confirmed revision after this copy's pending edits.
    pub fn map_presence(&self, mut at: super::Presence) -> Option<(super::Presence, crate::Selection)> {
        for (index, pending) in self.pending.iter().enumerate() {
            let moved = at.through(&pending.change, false)?;
            let later = || self.pending.iter().skip(index.saturating_add(1)).map(|p| &p.change);
            at = super::Presence {
                anchor: super::end_before(moved.anchor, later(), &self.document),
                focus: super::end_before(moved.focus, later(), &self.document),
            };
        }
        at.placed_in(&self.document, None)
    }

    pub fn needs_recovery(&self) -> bool {
        self.needs_recovery
    }

    /// Freeze edits and replay, for example if the server's replay cursor expired. The visible
    /// document and any uncertain submission remain available while the caller recovers.
    pub fn require_recovery(&mut self) {
        self.needs_recovery = true;
    }

    /// Apply a local edit optimistically. On refusal, the caller still owns the edit.
    pub fn queue(&mut self, change: &ChangeSet) -> Result<(), ReplicaError> {
        self.ready()?;
        if change.is_empty() {
            return Ok(());
        }
        let bytes = pending_size(&self.pending, change)?;
        let mut document = self.document.clone();
        apply(&mut document, change)?;
        self.pending.push_back(Pending { change: change.clone(), bytes });
        self.document = document;
        Ok(())
    }

    /// Start a proposal under a fresh, canonical operation ID generated by the transport.
    /// Until the journal confirms it, repeat the same proposal even after a disjoint edit moves
    /// its optimistic counterpart. A receipt tells the caller how far to fetch the journal.
    pub fn prepare(&mut self, operation_id: &str) -> Result<Option<&Proposal>, ReplicaError> {
        self.ready()?;
        if self.in_flight.is_none()
            && let Some(pending) = self.pending.front()
        {
            let change_json = serde_json::to_vec(&pending.change).map_err(ReplicaError::Encode)?;
            self.in_flight = Some(Proposal { operation_id: operation_id.to_owned(), base_revision: self.revision, change_json });
        }
        Ok(self.in_flight())
    }

    /// The exact request available for retry, even when local recovery is required.
    pub fn in_flight(&self) -> Option<&Proposal> {
        self.in_flight.as_ref()
    }

    /// Integrate an authoritative journal entry with a room-global operation ID. A remote change
    /// is returned mapped through the pending edits, so the caller can move selection and undo
    /// state in its editing session. The caller can fetch and retry on a gap. A clash leaves the
    /// local copy and pending queue available for explicit recovery.
    pub fn integrate(&mut self, revision: u64, operation_id: &str, change: &ChangeSet) -> Result<Option<ChangeSet>, ReplicaError> {
        if revision <= self.revision {
            return Ok(None);
        }
        self.ready()?;
        let expected = self.revision.saturating_add(1);
        if revision != expected {
            return Err(ReplicaError::Gap { expected, received: revision });
        }
        match self.apply_accepted(operation_id, change) {
            Ok(through) => {
                self.revision = revision;
                Ok(through)
            }
            Err(error) => {
                self.require_recovery();
                Err(error)
            }
        }
    }

    fn ready(&self) -> Result<(), ReplicaError> {
        if self.needs_recovery { Err(ReplicaError::RecoveryRequired) } else { Ok(()) }
    }

    fn apply_accepted(&mut self, operation_id: &str, change: &ChangeSet) -> Result<Option<ChangeSet>, ReplicaError> {
        let own = self.in_flight.as_ref().is_some_and(|p| p.operation_id == operation_id);
        let mut confirmed = self.confirmed.clone();
        apply(&mut confirmed, change)?;
        let through = if own {
            let pending = self.pending.front().ok_or(ReplicaError::AcceptedMismatch)?;
            if pending.change != *change {
                // The room recomputes fingerprints and position maps for the canonical entry.
                let mut expected = self.confirmed.clone();
                apply(&mut expected, &pending.change)?;
                if !confirmed.same_content(&expected) || confirmed.block_ids() != expected.block_ids() {
                    return Err(ReplicaError::AcceptedMismatch);
                }
            }
            self.pending.pop_front();
            self.in_flight = None;
            None
        } else if self.pending.is_empty() {
            self.document = confirmed.clone();
            Some(change.clone())
        } else {
            let mut through = change.clone();
            let mut moved = VecDeque::with_capacity(self.pending.len());
            for pending in &self.pending {
                let change = pending.change.rebase(&through, Side::After).map_err(ReplicaError::Conflict)?;
                through = through.rebase(&pending.change, Side::Before).map_err(ReplicaError::Conflict)?;
                let bytes = pending_size(&moved, &change)?;
                moved.push_back(Pending { change, bytes });
            }
            let mut document = self.document.clone();
            apply(&mut document, &through).map_err(ReplicaError::Conflict)?;
            self.pending = moved;
            self.document = document;
            Some(through)
        };
        self.confirmed = confirmed;
        Ok(through)
    }
}

/// Like the hub, check the inserted IDs on the candidate document before retaining it.
fn apply(document: &mut Document, change: &ChangeSet) -> wordcraft_doc::Result<()> {
    document.apply(change)?;
    if let Some(id) = document.repeated_id(&change.ids_put_in()) {
        return Err(DocError::Stale(format!("the change repeats block ID {id}")));
    }
    Ok(())
}

fn pending_size(pending: &VecDeque<Pending>, change: &ChangeSet) -> Result<usize, ReplicaError> {
    if pending.len() >= MAX_PENDING {
        return Err(ReplicaError::PendingLimit);
    }
    let mut size = ChangeSize(0);
    serde_json::to_writer(&mut size, change).map_err(|error| if error.is_io() { ReplicaError::PendingLimit } else { ReplicaError::Encode(error) })?;
    if pending.iter().map(|p| p.bytes).sum::<usize>().saturating_add(size.0) > MAX_PENDING_BYTES {
        return Err(ReplicaError::PendingLimit);
    }
    Ok(size.0)
}

struct ChangeSize(usize);

impl io::Write for ChangeSize {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        self.0 = self.0.saturating_add(bytes.len());
        if self.0 > MAX_CHANGE_BYTES {
            return Err(io::Error::other("change exceeds the room's byte limit"));
        }
        Ok(bytes.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

